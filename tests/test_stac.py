    assert all(acquisition_date(it) < FIRE_START for it in pre)
    assert all(acquisition_date(it) > FIRE_END for it in post)
    region = aoi.union_all()
    for side in (pre, post):
        assert unary_union([footprint(it) for it in side]).covers(region)

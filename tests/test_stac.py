"""Phase 1 test gates: scene selection with STAC (offline).

Fixture: tests/fixtures/stac/synthetic_search.json, generated by
make_synthetic.py in the same folder. Read that file's docstring for why each
item is there; the expected answers below follow from it.

The network is blocked for every test in this file.
"""
import random
import socket
from copy import deepcopy
from datetime import date
from pathlib import Path

import geopandas as gpd
import pytest
from shapely.geometry import box
from shapely.ops import unary_union

from burnsev.crs import CRSMismatchError
from burnsev.stac import (
    NoSceneError,
    acquisition_date,
    footprint,
    load_items,
    search_items,
    select_scenes,
)

FIXTURES = Path(__file__).parent / "fixtures" / "stac"
SYNTHETIC = FIXTURES / "synthetic_search.json"
REAL = FIXTURES / "palisades_search.json"  # you save this with scripts/save_stac_fixture.py

AOI_BOUNDS = (-118.68, 34.03, -118.50, 34.13)
FIRE_START = date(2025, 1, 7)
FIRE_END = date(2025, 1, 31)

EXPECTED_PRE = ["S2X_11SKT_20241228_0_L2A", "S2X_11SLT_20241228_0_L2A"]
EXPECTED_POST = ["S2X_11SKT_20250206_0_L2A", "S2X_11SLT_20250206_0_L2A"]


@pytest.fixture(autouse=True)
def no_network(monkeypatch):
    def refuse(*args, **kwargs):
        raise RuntimeError("network access attempted in an offline test")

    monkeypatch.setattr(socket.socket, "connect", refuse)
    monkeypatch.setattr(socket, "create_connection", refuse)


@pytest.fixture
def items():
    return load_items(SYNTHETIC)


@pytest.fixture
def aoi():
    return gpd.GeoSeries([box(*AOI_BOUNDS)], crs="EPSG:4326")


def ids(items):
    return [it["id"] for it in items]


def only(items, *days):
    keep = {date.fromisoformat(d) for d in days}
    return [it for it in items if acquisition_date(it) in keep]


# ---------------------------------------------------------------- fixture sanity

def test_fixture_loads(items):
    assert len(items) == 19
    assert len(set(ids(items))) == len(items)


# ---------------------------------------------------------------- core gate

def test_selects_expected_ids(items, aoi):
    pre, post = select_scenes(items, aoi, FIRE_START, FIRE_END)
    assert ids(pre) == EXPECTED_PRE
    assert ids(post) == EXPECTED_POST


def test_pre_strictly_before_post_strictly_after(items, aoi):
    pre, post = select_scenes(items, aoi, FIRE_START, FIRE_END)
    assert all(acquisition_date(it) < FIRE_START for it in pre)
    assert all(acquisition_date(it) > FIRE_END for it in post)


def test_every_returned_item_intersects_aoi(items, aoi):
    pre, post = select_scenes(items, aoi, FIRE_START, FIRE_END)
    region = aoi.union_all()
    for it in pre + post:
        assert footprint(it).intersects(region), it["id"]


def test_each_side_is_one_date_and_covers_aoi(items, aoi):
    pre, post = select_scenes(items, aoi, FIRE_START, FIRE_END)
    region = aoi.union_all()
    for side in (pre, post):
        assert len({acquisition_date(it) for it in side}) == 1
        assert unary_union([footprint(it) for it in side]).covers(region)


def test_respects_cloud_threshold(items, aoi):
    pre, post = select_scenes(items, aoi, FIRE_START, FIRE_END, max_cloud=20.0)
    assert all(it["properties"]["eo:cloud_cover"] <= 20.0 for it in pre + post)


# ---------------------------------------------------------------- individual rules

def test_fire_start_day_is_not_pre(items, aoi):
    # The 0%-cloud pair on 2025-01-07 must lose to 2024-12-20.
    pre, _ = select_scenes(only(items, "2024-12-20", "2025-01-07", "2025-02-06"), aoi, FIRE_START, FIRE_END)
    assert ids(pre) == ["S2X_11SKT_20241220_0_L2A", "S2X_11SLT_20241220_0_L2A"]


def test_scenes_during_fire_are_not_post(items, aoi):
    _, post = select_scenes(items, aoi, FIRE_START, FIRE_END)
    assert all(acquisition_date(it) != date(2025, 1, 20) for it in post)


def test_fire_end_defaults_to_fire_start(items, aoi):
    # Without a containment date, the clear 2025-01-20 pair becomes the best post scene.
    _, post = select_scenes(items, aoi, FIRE_START)
    assert ids(post) == ["S2X_11SKT_20250120_0_L2A", "S2X_11SLT_20250120_0_L2A"]


def test_partial_coverage_date_is_rejected(items, aoi):
    # 2025-01-02 has the clearest tile, but its partner tile fails the cloud filter.
    pre, _ = select_scenes(only(items, "2024-12-20", "2025-01-02", "2025-02-06"), aoi, FIRE_START, FIRE_END)
    assert acquisition_date(pre[0]) == date(2024, 12, 20)


def test_tile_missing_the_aoi_is_ignored(items, aoi):
    pre, post = select_scenes(items, aoi, FIRE_START, FIRE_END)
    assert not any("11SMT" in i for i in ids(pre + post))


def test_score_tie_goes_to_date_closest_to_fire(items, aoi):
    _, post = select_scenes(only(items, "2024-12-28", "2025-02-11", "2025-02-06"), aoi, FIRE_START, FIRE_END)
    assert acquisition_date(post[0]) == date(2025, 2, 6)


def test_deterministic_under_input_order(items, aoi):
    expected = select_scenes(items, aoi, FIRE_START, FIRE_END)
    shuffled = items[:]
    random.Random(0).shuffle(shuffled)
    assert select_scenes(shuffled, aoi, FIRE_START, FIRE_END) == expected


def test_does_not_mutate_input(items, aoi):
    before = deepcopy(items)
    select_scenes(items, aoi, FIRE_START, FIRE_END)
    assert items == before


# ---------------------------------------------------------------- failures are loud

def test_empty_input_raises(aoi):
    with pytest.raises(NoSceneError, match="pre-fire"):
        select_scenes([], aoi, FIRE_START, FIRE_END)


def test_all_cloudy_raises_and_names_threshold(items, aoi):
    with pytest.raises(NoSceneError, match=r"0\.1"):
        select_scenes(items, aoi, FIRE_START, FIRE_END, max_cloud=0.1)


def test_no_post_scene_raises(items, aoi):
    pre_only = [it for it in items if acquisition_date(it) < FIRE_START]
    with pytest.raises(NoSceneError, match="post-fire"):
        select_scenes(pre_only, aoi, FIRE_START, FIRE_END)


def test_only_partial_coverage_raises(items, aoi):
    with pytest.raises(NoSceneError, match="pre-fire"):
        select_scenes(only(items, "2025-01-02", "2025-02-06"), aoi, FIRE_START, FIRE_END)


# ---------------------------------------------------------------- CRS gates

def test_select_rejects_aoi_not_in_4326(items, aoi):
    with pytest.raises(CRSMismatchError):
        select_scenes(items, aoi.to_crs("EPSG:32611"), FIRE_START, FIRE_END)


def test_search_rejects_aoi_not_in_4326_before_network(aoi):
    # Must fail on the CRS check, not on the blocked network.
    with pytest.raises(CRSMismatchError):
        search_items(aoi.to_crs("EPSG:32611"), date(2024, 12, 1), date(2025, 1, 6))


# ---------------------------------------------------------------- real fixture

